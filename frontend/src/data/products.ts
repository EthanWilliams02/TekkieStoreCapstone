// Helper to map specific shoes to local images or brand-specific lifestyle imagery
const getShoeImage = (brand: string, name: string, id: string): string => {
  const lowerName = name.toLowerCase();
  
  if (lowerName.includes('air max 90')) return airMax90;
  if (lowerName.includes('monarch')) return airMonarch;
  if (lowerName.includes('530') || lowerName.includes('mr530')) return mr530;
  if (lowerName.includes('old skool')) return vansOldSkool;
  
  // Clean fallback assets from public matching brand aesthetic
  if (brand === 'Nike') {
    if (id.includes('women')) return '/category_women_sneakers.jpg';
    return '/trending_shoe_1_1788049696433.jpg';
  }
  if (brand === 'adidas') {
    if (id.includes('women')) return '/category_women_sneakers_orange.jpg';
    return '/trending_shoe_2_1788049708432.jpg';
  }
  if (brand === 'New Balance') {
    return '/trending_shoe_3_1788049721067.jpg';
  }
  if (brand === 'PUMA') {
    if (id.includes('women')) return '/category_women_sneakers_sitting_orange.jpg';
    return '/category_men_sneakers.jpg';
  }
  if (brand === 'Converse') {
    if (id.includes('women')) return '/category_women.jpg';
    return '/category_men_sneakers_sitting.jpg';
  }
  if (brand === 'Vans') {
    return vansOldSkool;
  }
  
  return '/category_sneakers_1788049733131.jpg';
};

